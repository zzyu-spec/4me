  assert.equal(await page.locator('.routine-stat-tabs').count(), 1);
  await page.click('[data-action="setRoutineStatsPeriod"][data-value="month"]');
  assert.equal(await page.locator('.routine-month-card').count(), 2);
  await page.click('[data-action="routineToday"]');
  await page.click('[data-action="routineManage"]');
  assert.equal(await page.locator('.routine-title').count(), 2);
  await page.evaluate(() => { state.selectedDate=todayISO(); setView('timeline'); });
  assert.equal(await page.locator('.timeline-head h2').textContent(), '타임라인');
  await page.click('[data-action="timelineNextWeek"]');
  await page.click('[data-action="timelineNextWeek"]');
  assert.equal(await page.evaluate(() => state.selectedDate), await page.evaluate(() => plusDays(todayISO(),14)));
  await page.click('[data-action="timelinePrevWeek"]');
  assert.equal(await page.evaluate(() => state.selectedDate), await page.evaluate(() => plusDays(todayISO(),7)));
  await page.fill('#timelineDate', await page.evaluate(() => todayISO()));
  await page.click('[data-action="newTimelineExtra"]');
  assert.equal(await page.locator('#timelineExtraForm select[name="category"]').inputValue(), '');
  assert(!await page.locator('#timelineExtraForm select[name="category"]').evaluate(el => el.required));
  await page.fill('#timelineExtraForm [name="title"]','분류 없는 활동');
  await page.locator('#timelineExtraForm>button.btn').click();
