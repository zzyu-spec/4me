  assert(!text.includes('데일리') && !text.includes(today.slice(0, 4)) && text.includes('실행·마감'));
  assert.equal(await page.locator('.todo-week .has-records').count(), 2);
  await page.locator('[data-section="과제"]').click();
  assert.equal(await page.locator('.todo-week .has-records').count(),1);
  await page.locator('[data-section="전체"]').click();
  assert.equal(await page.evaluate(()=>todoDisplayDate(todayISO().slice(0,4)+'-12-05')),'12/05');
  assert.equal(await page.evaluate(()=>todoDisplayDate((Number(todayISO().slice(0,4))-1)+'-12-05')),String(Number(today.slice(0,4))-1)+'/12/05');
  assert.equal(await page.locator('.todo-head-actions [data-action="manageSections"]').count(), 1);
  assert.equal(await page.locator('.todo-head-actions [data-action="toggleClosed"]').count(), 1);
  assert.equal(await page.locator('.todo-card [aria-label="투두 수정"] svg').count(), 1);
  assert.equal(await page.locator('.todo-card [aria-label="투두 삭제"] svg').count(), 1);
  await itemAction(page,'.todo-card [data-action="editTodo"]');
  await page.fill('#todoForm [name="title"]', '과제 수정');
  await page.locator('#todoForm>button.btn').click();
  await page.click('.todo-check');
  await page.click('[data-status="done"]');
  await page.click('[data-action="toggleClosed"]');
  assert.equal(await page.locator('.todo-card').count(), 0);
  await page.click('[data-action="toggleClosed"]');
  assert.equal(await page.locator('.todo-card').count(), 1);
  const tomorrow = await page.evaluate(() => plusDays(todayISO(), 1));
  await page.locator(`.todo-week [data-date="${tomorrow}"]`).click();
  assert.equal(await page.locator('.todo-card .body>strong').textContent(), '내일의 과제');
  await page.evaluate(() => {
    const d=todayISO();
    state.routines=[{id:'daily',title:'오늘 루틴',days:[],startDate:d},{id:'future',title:'미래 루틴',startDate:plusDays(d,10),days:[]}];
    state.selectedDate=plusDays(d,20); save(); setView('routines');
  });
  assert.equal(await page.locator('.routine-title').count(), 1);
  assert.equal(await page.locator('.routine-title').textContent(), '오늘 루틴');
  assert.equal(await page.locator('.routine-stat-tabs').count(), 0);
  await page.click('[data-action="newRoutine"]');
  assert.equal(await page.inputValue('#routineForm [name="startDate"]'),today);
  await page.click('[data-action="closeModal"]');
  await page.click('[data-action="routineDone"]');
